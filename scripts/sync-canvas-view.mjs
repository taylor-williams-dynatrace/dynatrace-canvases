#!/usr/bin/env node
/**
 * Mirror the read-only Canvas renderer from the app (the single source of truth)
 * into the publishable `@dynatrace-canvases/canvas-view` package.
 *
 * The app in `ui/app` remains canonical; this copies the closed set of files the
 * read-only render path needs into `packages/canvas-view/src`, preserving the
 * relative directory layout so their imports resolve unchanged. Package-only
 * files (index.ts, CanvasDocumentView.tsx) are never touched.
 *
 * Run: `npm run sync:canvas-view` (also part of `npm run build:canvas-view`).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appRoot = join(repoRoot, "ui", "app");
const pkgSrc = join(repoRoot, "packages", "canvas-view", "src");

// Files mirrored app -> package, keyed by their path relative to each root.
const FILES = [
  "types/metricsView.ts",
  "services/metricsQuery.ts",
  "components/TileShapeLayer.tsx",
  "components/MetricTile.tsx",
  "components/CanvasView.tsx",
  "hooks/useCanvasDocument.ts",
];

const BANNER =
  "/* AUTO-GENERATED by scripts/sync-canvas-view.mjs — do NOT edit here.\n" +
  " * Source of truth: ui/app/<same relative path>. Edit there, then run\n" +
  " * `npm run sync:canvas-view`. */\n\n";

let count = 0;
for (const rel of FILES) {
  const from = join(appRoot, rel);
  const to = join(pkgSrc, rel);
  const body = readFileSync(from, "utf8");
  mkdirSync(dirname(to), { recursive: true });
  writeFileSync(to, BANNER + body, "utf8");
  count += 1;
  console.log(`synced ${rel}`);
}
console.log(`\n${count} file(s) mirrored into packages/canvas-view/src`);
